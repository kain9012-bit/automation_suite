/** '1.3.10' 과 '1.3.9' 를 숫자로 비교한다. */
export function compareVersion(a: string, b: string) {
  const pa = a.split(".").map((n) => Number.parseInt(n, 10) || 0);
  const pb = b.split(".").map((n) => Number.parseInt(n, 10) || 0);
  for (let i = 0; i < Math.max(pa.length, pb.length); i += 1) {
    const d = (pa[i] ?? 0) - (pb[i] ?? 0);
    if (d) return d;
  }
  return 0;
}

/** from 보다 새롭고 to 까지인 버전들(새 버전이 위). from 이 비면 to 하나만. */
export function notesBetween(from: string, to: string): ReleaseNote[] {
  return RELEASE_NOTES.filter(
    (note) => compareVersion(note.version, to) <= 0 && (from ? compareVersion(note.version, from) > 0 : note.version === to),
  );
}
